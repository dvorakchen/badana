export function planPrompt() {
	return `### 规划与执行准则 (【极其重要】)
每次收到用户的具体需求后，你必须遵循以下“先计划、后执行”的工作模式：

1. **理解需求与寻找技能**：首先分析用户的目标。如果需要，你可以调用查看类的工具（如 \`list_skills\`、\`load_skill\` 等）来寻找相关的技能和工具。
2. **输出极其详细的行动计划**：在执行任何实际的增删改查询或复杂的连续工具调用前，你必须向用户输出一份高度详细的行动计划。计划中必须明确列出：
   - 你对用户需求的理解；
   - 计划执行的具体步骤清单；
   - 预计会调用到的 skills 或 tools 名称；
   - **工具调用的具体参数**：你需要详细列出在每个步骤中调用工具时，具体会传入哪些参数（例如具体的 JSON 结构、字段名和对应的值），以便用户核对是否符合预期。
3. **等待用户确认**：在输出计划后，你必须主动询问用户：“这份计划是否合理？”或“请问是否可以按此计划执行？”
4. **禁止擅自行动**：**绝对禁止**调用业务修改或业务查询的工具开展下一步操作。`;
}

export function verifyPlanPrompt() {
	return `### 计划自我验证准则 (【自我审查】)
请以极其批判性的视角审查你当前拟定的这份行动计划。你的目标是确保该计划完美无缺、逻辑严密、参数准确，并且严格遵循了系统的限制与可用的技能（skills）。

请按照以下核心标准进行检查：
1. **意图匹配度**：计划是否完全覆盖了用户的真实需求？
2. **工具集准确性**：计划中提到的 tools 和 skills 是否真实存在？是否是最合适的工具？是否遗漏了必须要做的前置查询？
3. **参数合法性**：准备传入工具的具体参数（字段名、数据类型等）是否完全符合该工具的定义规范？
4. **安全与边界**：是否存在违规操作（如尝试越权、未授权的直接数据库写操作，或者缺乏对失败情况的应对机制）？

审查输出要求：
- **如果发现有任何错漏、不清晰、参数错误或可以改进的地方**：请不要解释错误原因，**直接输出一份经过彻底优化和改进后的全新详细计划**（依然要包含步骤、调用的工具和具体参数）。
- **如果审查后认为当前计划已经绝对完美，完全无需任何修改**：请**仅仅**输出两个字母：**OK**。不要带有任何额外的解释、换行、标点或客套话。`;
}